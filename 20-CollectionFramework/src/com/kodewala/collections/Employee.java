package com.kodewala.collections;

public class Employee 
{
	String employeeId;
	String employeeName;
	String department;
	int salary;
	
	@Override
	public String toString() {
		return "Employee [employeeId=" + employeeId + ", employeeName=" + employeeName + ", department=" + department
				+ ", salary=" + salary + "]";
	}
	
	

}
